"""
Render everything a case needs to simulate, into tests/build/<cid>/:

    <macro>.v          the single-bank behavioural model, from OpenRAM's own
                       base/verilog.py writer (the "openram" model)
    <macro>_sync.v     the hand-edited fully-synchronous model that
                       rtl/weight_resolver/ actually uses (the "sync" model)
    <macro>_top.v      the wrapper under test
    dut_wrap.v         fixed-name shim so one testbench covers every case

Usage:
    python3 tests/render_cases.py [--wide] [cid ...]
"""

import argparse
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import cases  # noqa: E402
import orlib  # noqa: E402

BUILD = HERE / "build"

SYNC_MODEL = """// Fully synchronous single-clock SRAM model.
// This mirrors the hand-edited model in rtl/weight_resolver/, which differs
// from OpenRAM's generated one: all operations are on posedge so Vivado infers
// RAMB36E1. The wrapper must be correct against BOTH models, hence both are
// simulated.
module {name}(
`ifdef USE_POWER_PINS
    vdd,
    gnd,
`endif
    clk0,csb0,web0,addr0,din0,dout0
  );

  parameter DATA_WIDTH = {dw} ;
  parameter ADDR_WIDTH = {aw} ;
  parameter RAM_DEPTH = 1 << ADDR_WIDTH;

`ifdef USE_POWER_PINS
    inout vdd;
    inout gnd;
`endif
  input  clk0;
  input  csb0;
  input  web0;
  input [ADDR_WIDTH-1:0]  addr0;
  input [DATA_WIDTH-1:0]  din0;
  output [DATA_WIDTH-1:0] dout0;

  reg [DATA_WIDTH-1:0]    mem [0:RAM_DEPTH-1];
  reg [DATA_WIDTH-1:0]    dout0;

  always @(posedge clk0) begin
    if (csb0 == 1'b0) begin
      if (web0 == 1'b0) begin
        mem[addr0] <= din0;
      end else begin
        dout0 <= mem[addr0];
      end
    end
  end

endmodule
"""

DUT_WRAP = """// Generated by tests/render_cases.py -- fixed module name so a single
// testbench source covers every banking configuration.
module dut_wrap #(parameter DW = {dw}, parameter AW = {aw})
  (input clk0,
   input [AW-1:0] addr0,
   input [DW-1:0] din0,
   input csb0,
   input web0,
   output [DW-1:0] dout0);

  {top} u_dut (
    .clk0(clk0),
    .addr0(addr0),
    .din0(din0),
    .csb0(csb0),
    .web0(web0),
    .dout0(dout0));
endmodule
"""


def render(c):
    g = cases.geometry(c)
    name = cases.macro_name(c)
    out = BUILD / c.cid
    out.mkdir(parents=True, exist_ok=True)

    # 1. Wrapper under test, via the real sram_multibank.
    mb = orlib.multibank_class(banking_mode=c.mode)
    s = orlib.make_sram(c.word_size, c.num_words, c.num_banks,
                        h=c.h, v=c.v, name=name,
                        bank_addr_size=g["bank_addr_size"],
                        words_per_row=c.words_per_row)
    top_path = out / (name + "_top.v")
    mb(s).verilog_write(str(top_path))

    # 2. Bank models: OpenRAM's own writer, and the synchronous variant.
    orlib.write_bank_model(out / (name + ".v"), name,
                           word_size=g["bank_word_size"],
                           num_words=g["words_per_bank"],
                           bank_addr_size=g["bank_addr_size"])
    (out / (name + "_sync.v")).write_text(SYNC_MODEL.format(
        name=name, dw=g["bank_word_size"], aw=g["bank_addr_size"]))

    # 3. Fixed-name shim.
    (out / "dut_wrap.v").write_text(DUT_WRAP.format(
        dw=c.word_size, aw=g["top_addr_size"], top=name + "_top"))

    # 4. Parameters for the testbench / runner.
    (out / "params.sh").write_text(
        "MACRO={}\nW={}\nD={}\nH={}\nV={}\nAW={}\nMODE={}\n".format(
            name, c.word_size, c.num_words, c.h, c.v, g["top_addr_size"], c.mode))
    return out, name, g


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--wide", action="store_true",
                    help="also render the full-size 1024x2048 cases")
    ap.add_argument("cid", nargs="*", help="render only these case ids")
    a = ap.parse_args()

    if a.cid:
        selected = [cases.get(x) for x in a.cid]
    else:
        selected = cases.ALL if a.wide else cases.SMALL

    for c in selected:
        out, name, g = render(c)
        print("{:16s} {:10s} {}h x {}v -> macro {}b x {}w, "
              "bank_addr={} top_addr={} instances={}".format(
                  c.cid, c.mode, c.h, c.v, g["bank_word_size"],
                  g["words_per_bank"], g["bank_addr_size"],
                  g["top_addr_size"], g["instances"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
